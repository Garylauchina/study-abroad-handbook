"""Render the sourced catalog into browsable static pages and a small search index."""
from pathlib import Path
import argparse
import html
import json
import hashlib
import re
from urllib.parse import urlsplit
from catalog_inventory import load_inventories, coverage_text, inventory_markdown
from catalog_research import attach_research, profile_markdown

ROOT = Path(__file__).resolve().parents[1]
BASE = '/study-abroad-handbook/'
RANKING = json.loads((ROOT / 'data/rankings/qs-2027.json').read_text())
SECTIONS = [('overview', '专业说明'), ('admissions', '入学条件'), ('applications', '申请安排'), ('fees', '学费与资助'), ('outcomes', '毕业生情况')]

def esc(value):
    return html.escape(str(value), quote=True)

def route(country, university=None, program=None):
    parts = ['catalog', country]
    if university: parts.append(university)
    if program: parts.append(program)
    return '/'.join(parts) + '/'

def link(path, text, cls=''):
    return f'<a class="{cls}" href="{BASE}{path}">{esc(text)}</a>'

def load_catalog():
    countries, universities, programs = [], [], []
    for file in sorted((ROOT / 'data/catalog').glob('*.json')):
        data = json.loads(file.read_text())
        countries.append(data['country'])
        universities.extend(data['universities'])
        programs.extend(data['programs'])
    assert countries and programs, 'Catalog must contain real entries'
    for group in (countries, universities, programs):
        ids = [x['id'] for x in group]
        assert len(ids) == len(set(ids)), f'Duplicate IDs: {ids}'
        assert all(re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', x) for x in ids)
    cm, um = {c['id']: c for c in countries}, {u['id']: u for u in universities}
    for u in universities:
        assert u['country_id'] in cm and u['website'].startswith('https://')
    ranked = {r['name_en']: r for r in RANKING['rows'] if r['location'] != 'China (Mainland)' and r['rank'] <= 100}
    assert RANKING['edition'] == 2027 and len(RANKING['rows']) == 102
    assert len({r['name_en'] for r in RANKING['rows']}) == 102
    assert hashlib.sha256(json.dumps(RANKING['rows'], ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest() == RANKING['extracted_rows_sha256']
    assert len(ranked) == 96 and len(universities) == len(ranked)
    assert {u['qs_name_en'] for u in universities} == ranked.keys(), 'QS selection incomplete or contains extras'
    for u in universities:
        row = ranked[u['qs_name_en']]
        assert u['qs_rank'] == row['rank'] and u['qs_rank_display'] == row['rank_display']
        assert u['qs_year'] == 2027 and int(u['qs_rank_display'].lstrip('=')) == u['qs_rank']
        assert cm[u['country_id']]['qs_location'] == row['location']
    for p in programs:
        assert p['university_id'] in um
        for key in ['name', 'name_en', 'degree', 'subject', 'intake', 'duration', 'campus', 'language', 'entry_summary', 'tuition_summary', 'outcomes_summary', 'checked_at']:
            assert isinstance(p[key], str) and p[key].strip(), f'{p["id"]}: missing {key}'
        assert re.fullmatch(r'\d{4}-\d{2}-\d{2}', p['checked_at'])
        sources = {s['id']: s for s in p['sources']}
        assert sources and len(sources) == len(p['sources'])
        for s in sources.values():
            assert re.fullmatch(r'[a-zA-Z0-9-]+', s['id']), s['id']
            assert urlsplit(s['url']).scheme == 'https' and s['title'] and s['supports']
            assert s['checked_at'] == p['checked_at']
        cited = set()
        for key, _ in SECTIONS:
            assert p['sections'][key], f'{p["id"]}: empty section {key}'
            for fact in p['sections'][key]:
                assert fact['label'] and fact['text'] and fact['source_ids']
                assert set(fact['source_ids']) <= sources.keys(), f'{p["id"]}: broken source reference'
                cited.update(fact['source_ids'])
        assert cited == sources.keys(), f'{p["id"]}: unused sources {sources.keys() - cited}'
    programs = load_inventories(ROOT, universities, programs)
    attach_research(ROOT, universities, programs)
    return countries, universities, programs

def front(title, wide=False, program_context=None):
    hidden = ['toc', 'navigation'] if wide else ['toc']
    context = ''.join(key+': '+json.dumps(value,ensure_ascii=False)+'\n' for key,value in (program_context or {}).items())
    return '---\ntitle: ' + json.dumps(title, ensure_ascii=False) + '\n'+context+'hide:\n' + ''.join('  - '+x+'\n' for x in hidden) + '---\n\n<!-- Generated by scripts/render_catalog.py; edit data/catalog, data/program-index or data/program-research. -->\n\n'

def crumbs(items):
    return '<nav class="catalog-crumbs" aria-label="浏览路径">' + ' <span aria-hidden="true">/</span> '.join(link(p,t) if p is not None else f'<span aria-current="page">{esc(t)}</span>' for p,t in items) + '</nav>\n\n'

def rank_badge(u, program=False):
    label = '大学 QS 2027' if program else 'QS 2027'
    return f'<span class="qs-rank">{label} · <strong>{esc(u["qs_rank_display"])}</strong></span>'

def program_card(p, u, c):
    depth = '仅补学校共用资料' if p.get('research_scope') == 'school' else {'detailed':'含详细资料','enriched':'部分专业资料已核实','directory':'目录已核对 · 详情待补'}[p['detail_status']]
    secondary = p['name_en'] if p['name'] != p['name_en'] else p.get('degree_label', p['degree'])
    cohort = p['intake']+' 入学' if p['intake'] != '尚未核实' else '入学年度待核实'
    facts = '<dl class="program-facts">'+''.join('<dt>'+label+'</dt><dd>'+esc(p[key])+'</dd>' for label,key in [('入学','entry_summary'),('学费','tuition_summary'),('毕业','outcomes_summary')])+'</dl>' if p['detail_status']=='detailed' else '<p class="directory-note">'+esc(p['entry_summary'])+'</p>'
    return f'''<article class="program-card" data-program-id="{p['id']}">
<div class="program-meta"><span>{esc(c['name'])} · {esc(u['city'])}</span><span>{esc(p['subject'])}</span></div>
<p class="program-school">{link(route(c['id'],u['id']), u['name'])}</p>
{rank_badge(u, True)} <span class="program-depth">{depth}</span>
<h3>{link(route(c['id'],u['id'],p['id']), p['name'])}</h3>
<p class="program-english">{esc(secondary)}</p>
<p class="program-cohort">{esc(cohort)} · {esc(p['degree'])}</p>
{facts}
{link(route(c['id'],u['id'],p['id']), '查看条件、费用与去向 →', 'program-open')}
</article>'''

def university_card(u, c, programs):
    ps = [p for p in programs if p['university_id'] == u['id']]
    status = coverage_text(ps) if ps else '专业详情待收录'
    return f'''<article class="university-card" data-university-id="{u['id']}">{rank_badge(u)}<p class="catalog-eyebrow">{esc(c['name'])} · {esc(u['city'])}</p><h2>{link(route(c['id'], u['id']), u['name'])}</h2><p class="university-english">{esc(u['name_en'])}</p><p class="university-coverage">{status}</p>{link(route(c['id'],u['id']),"查看学校与专业入口 →","program-open")}</article>'''

