    home += ''.join(f'<option value="{c["id"]}">{esc(c["name"])}</option>' for c in countries)
    home += '</select></label><label>大学<select id="catalog-university" name="university"><option value="">全部大学</option>' + ''.join(f'<option value="{u["id"]}" data-country="{u["country_id"]}">{esc(u["name"])}</option>' for u in universities) + '</select></label><label id="catalog-subject-label">专业方向<select id="catalog-subject" name="subject"><option value="">全部方向</option>' + ''.join(f'<option value="{esc(subject)}">{esc(subject)}</option>' for subject in sorted({s for p in programs for s in p.get('subjects',[p['subject']])})) + '</select></label><label id="catalog-depth-label">资料深度<select id="catalog-depth" name="depth"><option value="">全部条目</option><option value="detailed">含详细资料</option><option value="enriched">含部分资料</option><option value="directory">目录已核对</option></select></label><button type="reset">清除筛选</button></form>\n'
    home += '<noscript><style>.catalog-filters{display:none}</style><p>可通过国家入口和下面的大学、专业链接直接浏览。启用 JavaScript 后可使用即时筛选。</p></noscript>'
    home += f'<p class="catalog-status" id="catalog-status" role="status" aria-live="polite">收录 QS 2027 前 100 名的 {len(universities)} 所非中国大陆大学，按原始名次排序；“=”表示并列。</p><p id="catalog-empty" hidden></p><div id="catalog-results"><section id="catalog-universities"><h3 class="catalog-list-title">大学清单</h3><div class="university-grid">'
